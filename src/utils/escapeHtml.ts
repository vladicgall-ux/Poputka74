/**
 * Экранирует текст для вставки в HTML-сообщения бота (Telegram/MAX оба
 * используют parse_mode/format 'html' с одинаковым ограниченным набором
 * тегов). Без этого любой пользовательский текст, попавший в такое
 * сообщение (имя, текст в поддержку, комментарий к поездке и т.п.), может:
 * 1) сломать разбор сообщения одиночным "<"/">" — Telegram/MAX отвечают
 *    ошибкой "can't parse entities" на весь sendMessage, и уведомление
 *    (например, о новой брони) тихо не доходит до адресата;
 * 2) внедрить настоящий кликабельный тег (например <a href="...">) в
 *    сообщение, которое выглядит как сгенерированное ботом — фишинг под
 *    видом системного уведомления.
 * Экранировать нужно только "&", "<", ">" — остальные HTML-мета-символы
 * (кавычки и т.п.) не имеют значения вне атрибутов тегов, а мы их не строим
 * из пользовательского ввода.
 */
export function escapeTgHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
